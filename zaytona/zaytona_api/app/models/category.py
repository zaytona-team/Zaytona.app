"""CATEGORY model — reference data for grocery items.

Categories are pre-seeded (16 default grocery aisle categories) and
used to:
  * Group items in the catalog (US-18)
  * Organize the buying view by store aisle sequence (US-26)

They are read-only from the API — no create/update/delete endpoints.
The `sort_order` column defines the standard store aisle sequence
used by the buying view.

Validation rules (per documentation):
  * name is required (nullable=False)
  * name is unique (no duplicate categories)
  * sort_order is required for aisle sequencing
"""
from sqlalchemy.orm import validates

from app.extensions import db
from app.models.base_model import UUIDType, gen_uuid
from app.utils.validators import require_text


class Category(db.Model):
    __tablename__ = "categories"

    # Primary key — UUID generated by gen_uuid()
    category_id = db.Column(UUIDType, primary_key=True, default=gen_uuid)

    # Human-readable name (unique, indexed for fast lookups)
    # Validation: required (nullable=False), unique
    name = db.Column(db.String(80), unique=True, nullable=False, index=True)

    # Optional icon/image URL for UI display
    image_url = db.Column(db.String(512), nullable=True)

    # Sort order for the standard store aisle sequence (US-26).
    # Lower numbers appear first in the buying view.
    # Validation: required (nullable=False)
    sort_order = db.Column(db.Integer, nullable=False, default=0, index=True)

    @validates("name")
    def _validate_name(self, _key, value):
        return require_text(value, "name", max_length=80)

    def to_dict(self) -> dict:
        """Serialize the category to a JSON-friendly dictionary."""
        return {
            "category_id": self.category_id,
            "name": self.name,
            "image_url": self.image_url,
            "sort_order": self.sort_order,
        }