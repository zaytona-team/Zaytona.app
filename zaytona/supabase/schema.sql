-- USER -----------------------------------------------------------
create table if not exists public.users (
    user_id     uuid primary key,
    first_name  varchar(80),
    last_name   varchar(80),
    email       varchar(255) unique,
    phone       varchar(32)  unique,
    avatar_url  varchar(512),
    phone_verified boolean not null,
    created_at  timestamptz not null,
    updated_at  timestamptz not null
);

-- GROUP / GROUP_MEMBER (US-04..US-10) ----------------------------
do $$ begin
    create type group_type as enum ('individual', 'household');
exception when duplicate_object then null;
end $$;

do $$ begin
    create type group_role as enum ('admin', 'member');
exception when duplicate_object then null;
end $$;

create table if not exists public.groups (
    group_id    uuid primary key,
    created_by  uuid not null references public.users(user_id),
    name        varchar(120) not null,
    image_url   varchar(512),
    icon        varchar(32),
    type        group_type not null,
    invite_code varchar(16) unique,
    created_at  timestamptz not null,
    updated_at  timestamptz not null
);

create table if not exists public.group_members (
    member_id   uuid primary key,
    group_id    uuid not null references public.groups(group_id),
    user_id     uuid not null references public.users(user_id),
    role        group_role not null,
    joined_at   timestamptz not null,
    constraint uq_group_member unique (group_id, user_id)
);

-- SHOPPING_LIST / RECIPE ------------------------------------------
-- Fleshed out early (ahead of their own stories) only so that
-- Group Management's US-11/US-12 admin-delete endpoints have real
-- tables to act on. Full columns/behaviour land with List
-- Management (US-13+) and Recipes (US-33+).
do $$ begin
    create type shopping_list_status as enum ('active', 'completed');
exception when duplicate_object then null;
end $$;

create table if not exists public.shopping_lists (
    list_id      uuid primary key,
    group_id     uuid not null references public.groups(group_id),
    created_by   uuid not null references public.users(user_id),
    completed_by uuid references public.users(user_id),
    name         varchar(120) not null,
    status       shopping_list_status not null,
    created_at   timestamptz not null,
    updated_at   timestamptz not null,
    completed_at timestamptz,
    color        varchar(20)
);

create table if not exists public.recipes (
    recipe_id        uuid primary key,
    group_id         uuid not null references public.groups(group_id),
    created_by       uuid not null references public.users(user_id),
    -- Set when this row is a group's own customized copy of a recipe-book
    -- recipe ("add to a group" forks a copy instead of mutating the
    -- original) — null for a recipe created directly in the group.
    source_recipe_id uuid references public.recipes(recipe_id),
    name             varchar(120) not null,
    image_url        varchar(512),
    type             varchar(60),
    description      text,
    created_at       timestamptz not null,
    updated_at       timestamptz not null
);

